"""Project the overlay onto PROV-O.

The paper's discussion admits the gap: records carry what PROV-O would express - the tool
run, its method, its inputs, their digests - but in the overlay's own vocabulary, so a
consumer has to learn this project's terms. This module closes it the cheap way, as a
projection rather than a redesign.

The mapping, and why:

    artifact digest   prov:Entity            the thing that was used
    tool run          prov:Activity          something that happened, at a time, with a tool
    review            prov:Activity          also an activity: a person did something
    assertion         prov:Entity            produced by an activity, derived from a baseline
    baseline          prov:Entity            a collection whose members are the artifacts
    tool / reviewer   prov:Agent             attributed responsibility

One mapping decision worth stating: an assertion is an Entity generated by an Activity
rather than an Activity itself. A claim is a thing that exists and can be cited; the tool
run that produced it is the event. Reversing those makes `prov:wasGeneratedBy` point the
wrong way, which is the commonest way a provenance graph ends up unqueryable.
"""
from __future__ import annotations

from .ledger import Ledger
from .model import Assertion, InterfaceCheck, ManualReview, ToolRun

PREFIXES = """@prefix prov: <http://www.w3.org/ns/prov#> .
@prefix dcterms: <http://purl.org/dc/terms/> .
@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .
@prefix dt: <urn:digital-thread:> .
"""


def _esc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def _assertion_nodes(a: Assertion, seen_agents: set[str]) -> str:
    """One assertion: the claim, the activity behind it, and what both touched."""
    lines = []
    claim = f"dt:claim-{a.id.removeprefix('as:')}"
    baseline = f"dt:baseline-{a.baseline.removeprefix('bl:')}"

    lines.append(f"{claim} a prov:Entity ;")
    lines.append(f'    dcterms:identifier "{_esc(a.id)}" ;')
    lines.append(f'    dt:subject "{_esc(a.subject)}" ;')
    lines.append(f'    dt:predicate "{_esc(a.predicate)}" ;')
    lines.append(f'    dt:object "{_esc(a.object)}" ;')
    lines.append(f'    dt:evidenceLevel "{a.level.value}" ;')
    lines.append(f'    dt:status "{a.status.value}" ;')
    lines.append(f"    prov:used {baseline} ;")
    lines.append(f'    prov:generatedAtTime "{a.created}"^^xsd:dateTime .')
    lines.append("")

    activity_names = []
    for i, evidence in enumerate(a.evidence):
        act = f"{claim}-activity-{i}"
        activity_names.append(act)
        lines.append(f"{act} a prov:Activity ;")
        lines.append(f'    prov:startedAtTime "{a.created}"^^xsd:dateTime ;')
        lines.append(f"    prov:used {baseline} ;")
        if isinstance(evidence, ToolRun):
            agent = f"dt:tool-{_slug(evidence.tool)}"
            lines.append(f"    prov:wasAssociatedWith {agent} ;")
            lines.append(f'    dt:method "{_esc(evidence.method)}" ;')
            if evidence.passed is not None:
                lines.append(f"    dt:passed {str(evidence.passed).lower()} ;")
            if evidence.output_digest:
                lines.append(f'    dt:outputDigest "{_esc(evidence.output_digest)}" ;')
        elif isinstance(evidence, InterfaceCheck):
            lines.append(f'    dt:method "interface check: {_esc(evidence.check)}" ;')
            if evidence.passed is not None:
                lines.append(f"    dt:passed {str(evidence.passed).lower()} ;")
        elif isinstance(evidence, ManualReview):
            agent = f"dt:reviewer-{_slug(evidence.reviewer)}"
            lines.append(f"    prov:wasAssociatedWith {agent} ;")
            lines.append(f'    dt:method "manual review" ;')
            if evidence.note:
                lines.append(f'    dcterms:description "{_esc(evidence.note)}" ;')
        # close the last predicate with a full stop
        lines[-1] = lines[-1].rstrip(" ;") + " ."
        lines.append("")

        if isinstance(evidence, (ToolRun, ManualReview)):
            who = evidence.tool if isinstance(evidence, ToolRun) else evidence.reviewer
            kind = "prov:SoftwareAgent" if isinstance(evidence, ToolRun) else "prov:Person"
            node = agent
            # an agent appears once in the graph, however many claims it touched: repeating
            # the block per claim bloats the Turtle without adding a triple
            if node not in seen_agents:
                seen_agents.add(node)
                lines.append(f"{node} a {kind} ;")
                lines.append(f'    dcterms:title "{_esc(who)}" .')
                lines.append("")

    if activity_names:
        lines[-1:] = [f"{claim} prov:wasGeneratedBy {activity_names[-1]} .", ""]
    return "\n".join(lines)


def _slug(text: str) -> str:
    return "".join(c if c.isalnum() or c in "-_" else "-" for c in str(text)).strip("-").lower()


def project(ledger: Ledger, include_artifacts: bool = True) -> str:
    """The whole ledger as a PROV-O graph, as Turtle."""
    out = [PREFIXES]
    seen_agents: set[str] = set()
    seen_baselines = set()
    seen_artifacts = set()

    for a in ledger.assertions():
        if a.baseline not in seen_baselines:
            seen_baselines.add(a.baseline)
            try:
                baseline = ledger.get_baseline(a.baseline)
            except KeyError:
                baseline = None
            node = f"dt:baseline-{a.baseline.removeprefix('bl:')}"
            out.append(f"{node} a prov:Entity, prov:Collection ;")
            out.append(f'    dcterms:identifier "{a.baseline}" ;')
            if baseline and baseline.created:
                out.append(f'    prov:generatedAtTime "{baseline.created}"^^xsd:dateTime ;')
            out.append("    .")
            out.append("")
            if include_artifacts and baseline:
                for art in baseline.artifacts:
                    dig = f"dt:artifact-{art.sha256[:16]}"
                    if dig not in seen_artifacts:
                        seen_artifacts.add(dig)
                        out.append(f"{dig} a prov:Entity ;")
                        out.append(f'    dcterms:identifier "{art.kind}:{art.sha256}" ;')
                        out.append(f'    dt:kind "{art.kind}" ;')
                        out.append(f"    .")
                        out.append("")
                    out.append(f"{node} prov:hadMember {dig} .")
                    out.append(f"{dig} prov:value \"{art.sha256}\" .")
                out.append("")
        out.append(_assertion_nodes(a, seen_agents))

    return "\n".join(out).rstrip() + "\n"
