# ---- adapters ---------------------------------------------------------------
def test_step_adapter_extracts_header_and_products(step_file):
    e = adapters.extract(step_file)
    keys = {f.key for f in e.facts}
    assert "step:schema" in keys, "the schema edition is the fact that dates the file"
    assert "step:product" in keys, "a product structure with no products is not a thread"
    assert e.sha256 == baselines.file_digest(step_file)
    # every fact says how it was obtained: a fact with no method is a guess
    assert all(f.method for f in e.facts)


def test_step_adapter_does_not_overclaim(step_file):
    """It scans lines; it must not present itself as a parser."""
    e = adapters.extract(step_file)
    assert e.adapter.startswith("step-header-scan"), e.adapter
    assert not any("geometry" in f.key for f in e.facts)


def test_unhandled_kind_falls_back_to_identity_only(tmp_path):
    odd = tmp_path / "notes.txt"
    odd.write_text("something the overlay knows nothing about\n")
    e = adapters.extract(odd)
    assert e.adapter == "identity-only/1"
    assert e.facts == [], "no facts is the honest answer for an unknown format"
    assert len(e.sha256) == 64


def test_sidecar_round_trip_and_staleness(step_file):
    adapter = adapters.SidecarAdapter()
    facts = [adapters.Fact(key="owner", value="jrf", method="manual entry", anchor="n/a")]
    side = adapter.write(step_file, facts)
    assert side.exists()

    first = adapter.extract(step_file)
    assert any(f.key == "owner" and f.value == "jrf" for f in first.facts)

    # change the artifact without regenerating the sidecar: the digest disagreement must show
    step_file.write_text(step_file.read_text() + "\n/* edited */\n")
    second = adapter.extract(step_file)
    assert any(f.key == "sidecar-stale" for f in second.facts), \
        "a sidecar describing older content must be detectable, not silently authoritative"


def test_sidecar_never_modifies_the_artifact(step_file):
    before = step_file.read_bytes()
    adapters.SidecarAdapter().write(step_file, [])
    assert step_file.read_bytes() == before, "the sidecar pattern exists to leave files alone"


# ---- PROV-O -----------------------------------------------------------------
@pytest.fixture()
def ledger_with_claim(tmp_path, step_file):
    ledger = Ledger(tmp_path / ".overlay")
    b = baselines.create([step_file])
    ledger.put_baseline(b)
    ledger.set_current(b.id)
    a = Assertion(source_anchor="urn:test:anchor", subject="urn:sysml:Vehicle", predicate="correspondsToProduct",
                  object="urn:step242:CTC-01", baseline=b.id, level=Level.STRUCTURE)
    ledger.append(a)
    return ledger, a


def test_projection_has_the_directions_that_make_it_queryable(ledger_with_claim):
    ledger, a = ledger_with_claim
    ttl = prov.project(ledger)
    claim = f"dt:claim-{a.id.removeprefix('as:')}"
    assert f"{claim} a prov:Entity" in ttl, "a claim is a thing, not an event"
    # the claim's predicates are one statement block, so check the block, not a single line
    block = ttl.split(f"{claim} a prov:Entity")[1].split("\n\n")[0]
    assert "prov:used dt:baseline-" in block, \
        "the claim must say which revision it was made against"
    assert "prov:hadMember" in ttl, "the baseline must name its members"
    assert "prov:SoftwareAgent" not in ttl  # no tool run on this claim yet


def test_projection_records_a_tool_run_as_an_activity_with_an_agent(tmp_path, step_file):
    from digital_thread_overlay import operations
    ledger = Ledger(tmp_path / ".overlay")
    b = baselines.create([step_file])
    ledger.put_baseline(b)
    ledger.set_current(b.id)
    a = Assertion(source_anchor="urn:test:anchor", subject="s", predicate="p", object="o", baseline=b.id)
    ledger.append(a)
    operations.promote(ledger, a, operations.tool_run("step242", "structure-check",
                                                      passed=True, version="0.4.0"))
    ttl = prov.project(ledger)
    assert "prov:Activity" in ttl
    assert "prov:SoftwareAgent" in ttl
    assert 'dt:passed true' in ttl
    assert "dt:method \"structure-check\"" in ttl


def test_projection_parses_as_turtle_if_rdflib_is_available(ledger_with_claim):
    ledger, _ = ledger_with_claim
    ttl = prov.project(ledger)
    rdflib = pytest.importorskip("rdflib")
    g = rdflib.Graph()
    g.parse(data=ttl, format="turtle")
    assert len(g) > 5
    from rdflib.namespace import Namespace
    PROV = Namespace("http://www.w3.org/ns/prov#")
    claims = list(g.subjects(rdflib.RDF.type, PROV.Entity))
    assert any("claim" in str(s) for s in claims)


def test_every_assertion_appears_once_in_the_projection(ledger_with_claim):
    ledger, a = ledger_with_claim
    ttl = prov.project(ledger)
    claim = f"dt:claim-{a.id.removeprefix('as:')}"
    assert ttl.count(f"{claim} a prov:Entity") == 1
